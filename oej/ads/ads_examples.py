def classify_ads():
    from oej.ads.meta_api import LoadMetaAds

    load_meta = LoadMetaAds(limit=2000)
    load_meta.classify_ads(limit=2000)
    load_meta.save_ads()
    load_meta.save_list_ads()

    load_meta.classify_duplicate_ads()
    load_meta.save_ads()
    load_meta.save_list_ads()


