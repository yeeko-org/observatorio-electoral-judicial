def load_winners():
    from oej.models import Candidate
    Candidate.objects.filter(seat__position__by_circuit=False).update(
        real_winner=False,
        real_winner_final=False,
        real_winner_circuit=False
    )
    for winner_id in winners:
        candidate = Candidate.objects.filter(id=winner_id).first()
        if candidate:
            candidate.real_winner = True
            candidate.real_winner_final = True
            candidate.real_winner_circuit = True
            candidate.save()
        else:
            print(f"Candidate with ID {winner_id} not found.")

